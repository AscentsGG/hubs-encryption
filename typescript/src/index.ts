/**
 * End-to-end encrypted private conversations on MLS (RFC 9420), built on
 * ts-mls. This file is the package's only entry point.
 *
 * - protocol: constants, the bytes each signature and commitment covers,
 *   the key package lifetime policy and the payload rules every client
 *   applies.
 * - engine: identity and device keys, key packages, MLS groups, encrypting
 *   and receiving, safety codes, linking a device and the passkey backup.
 * - client: what one device does against the server, given a transport
 *   function and a key-value store.
 * - idb-store: the IndexedDB store, sealed at rest with a non-extractable
 *   WebCrypto key, and the passkey PRF secret for browsers.
 * - calls: end-to-end encrypted calls bound to the same identities: the
 *   connection statements, wrapped call keys, codes, roster statements and
 *   the rule for who gets the call key. It loads no MLS code.
 */
